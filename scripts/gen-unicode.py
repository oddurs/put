#!/usr/bin/env python3
"""Generate src/unicode_tables.h from Unicode character properties.

  python3 scripts/gen-unicode.py > src/unicode_tables.h
  make check-unicode      # regenerate and fail if the file is out of date

Uses the Unicode data bundled with the `regex` package, which tracks new
Unicode versions quickly. The version is pinned in tests/requirements.txt
(pip install -r tests/requirements.txt) so the output is reproducible;
REGEX_VERSION below must match it, and the script refuses to run otherwise.

Two sets are produced:

  INVISIBLE  code points put.peek and put.quote always escape, because they
             have no glyph of their own, render as blank space, or render
             differently depending on the font:
               Cc  controls (C1 only; C0 and DEL are handled separately)
               Cf  format characters (zero-width, bidi controls, tags, ...)
               Cn  unassigned code points and noncharacters
               Co  private use (icon fonts and the like)
               Zs  space separators other than U+0020
               Zl  line separator,  Zp  paragraph separator
               Default_Ignorable_Code_Point (variation selectors, Hangul
                   fillers, combining grapheme joiner, ...)
               U+2800 BRAILLE PATTERN BLANK, U+1D159 MUSICAL SYMBOL NULL
                   NOTEHEAD: graphic characters that render as nothing
  COMBINING  General_Category M (Mn, Mc, Me): marks that draw on top of the
             character before them. Escaped only when there is no visible
             character before them to attach to.
"""

import sys

import regex

REGEX_VERSION = "2026.9.29"

INVISIBLE = regex.compile(
    r"[\p{Cc}\p{Cf}\p{Cn}\p{Co}\p{Zs}\p{Zl}\p{Zp}\p{Default_Ignorable_Code_Point}"
    r"⠀\U0001D159]"
)
COMBINING = regex.compile(r"\p{M}")

# Characters first assigned in each Unicode version, newest first; the first
# one the data knows about names the version.
VERSION_PROBES = [("17.0", 0x10940), ("16.0", 0x10D40), ("15.1", 0x2EBF0), ("15.0", 0x11F00)]


def unicode_version() -> str:
    unassigned = regex.compile(r"\p{Cn}")
    for version, cp in VERSION_PROBES:
        if not unassigned.match(chr(cp)):
            return version
    return "older than 15.0"


def ranges(pattern, lo: int) -> list:
    out = []
    start = None
    for cp in range(lo, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue  # surrogates never come out of the UTF-8 decoder; don't split on them
        hit = pattern.match(chr(cp)) is not None
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name: str, rs: list, what: str) -> str:
    lines = [f"/* {what}: {len(rs)} ranges. */", f"static const utf8_range {name}[] = {{"]
    row = []
    for a, b in rs:
        row.append(f"{{0x{a:X}, 0x{b:X}}},")
        if len(" ".join(row)) > 88:
            lines.append("    " + " ".join(row[:-1]))
            row = row[-1:]
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    if regex.__version__ != REGEX_VERSION:
        print(f"regex {regex.__version__} is installed, but the table is made with "
              f"{REGEX_VERSION}: pip install -r tests/requirements.txt", file=sys.stderr)
        return 1
    version = unicode_version()
    invisible = ranges(INVISIBLE, 0x80)
    combining = ranges(COMBINING, 0x80)

    print(f"""/*
 * unicode_tables.h — character classes for put.peek and put.quote.
 *
 * GENERATED by scripts/gen-unicode.py from Unicode {version} data
 * (Python regex package {regex.__version__}). Do not edit by hand: change the
 * script and run `python3 scripts/gen-unicode.py > src/unicode_tables.h`.
 * `make check-unicode` fails if this file is out of date.
 *
 * Each table is a sorted list of inclusive [first, last] code point ranges,
 * searched with a binary search in utf8.c. The script's comments say what
 * each table contains and why.
 */
#ifndef PUT_UNICODE_TABLES_H
#define PUT_UNICODE_TABLES_H

#include <stdint.h>

typedef struct {{
    uint32_t first;
    uint32_t last;
}} utf8_range;

#define PUT_UNICODE_VERSION "{version}"

{emit("INVISIBLE_RANGES", invisible, "Escaped everywhere")}

{emit("COMBINING_RANGES", combining, "Escaped when there is nothing to attach to")}

#endif""")
    return 0


if __name__ == "__main__":
    sys.exit(main())
